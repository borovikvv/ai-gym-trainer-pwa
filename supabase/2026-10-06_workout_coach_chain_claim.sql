-- Issue #408: защита от повторного LLM-прогона цепочки тренера.
--
-- Сохранение тренировки больше не ждёт тяжёлую цепочку тренера (анализ,
-- планирование, нарратор, обучающая запись): тренировка коммитится, ответ
-- отдаётся 201, а цепочка уходит в фон. Повтор запроса из офлайн-очереди
-- (или обрыв соединения после отправки) не должен запускать её второй раз —
-- иначе дублируются дорогие LLM-вызовы и вывод плана.
--
-- coach_chain_claimed_at — отметка «цепочка по этой сессии уже запущена».
-- Условный UPDATE ... where coach_chain_claimed_at is null в той же
-- транзакции, что и запись тренировки, атомарно выбирает ровно одного
-- победителя: остальные повторы видят колонку занятой и цепочку не гонят.
alter table public.workout_sessions
  add column if not exists coach_chain_claimed_at timestamptz;

comment on column public.workout_sessions.coach_chain_claimed_at is
  'Issue #408: когда для сессии был запущен фоновый прогон цепочки тренера. Не null — повторный POST не пересчитывает LLM-цепочку.';
